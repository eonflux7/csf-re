#!/usr/bin/env python3
"""Generate standalone/adjustors.cpp: the exe's this-adjustor thunks (`sub ecx, N; jmp target`) as naked functions.

  gen_adjustors.py          write the file (and print the count)
  gen_adjustors.py --check  exit 1 if the file is stale

IDA leaves these 8-byte thunks outside any function, so db/functions.csv has none of them and the standalone filled
their vtable slots with traps ("not-a-function"): skipping the intro called 0x4F0E70 (secondary vtable 0x83EF10).
Candidates are the not-a-function slots of build/cutover/stubs.json plus every vtable slot in the data image; each
must decode to exactly `sub ecx, imm` + `jmp rel32`. Thunks already supplied by hand elsewhere are skipped.
"""
import json, os, re, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "standalone", "adjustors.cpp")


def thunks():
    import pefile
    pe = pefile.PE(os.path.join(ROOT, "work", "pc", "CommXPC.exe"), fast_load=True)
    img = pe.get_memory_mapped_image()
    text = next(s for s in pe.sections if s.Name.startswith(b".text"))
    t0, t1 = 0x400000 + text.VirtualAddress, 0x400000 + text.VirtualAddress + text.Misc_VirtualSize
    cands = {int(s["address"], 16) for s in json.load(open(os.path.join(ROOT, "build/cutover/stubs.json")))["slots"]
             if s["kind"] == "not-a-function"}
    for off in range(0x82D000 - 0x400000, len(img) - 4, 4):  # vtable slots: words in the data image into .text
        w = struct.unpack_from("<I", img, off)[0]
        if t0 <= w < t1:
            cands.add(w)
    out = {}
    for a in sorted(cands):
        o = a - 0x400000
        b = img[o:o + 11]
        if b[:2] == b"\x83\xE9" and b[3] == 0xE9:      # sub ecx, imm8; jmp rel32
            n, rel, size = b[2], struct.unpack_from("<i", b, 4)[0], 8
        elif b[:2] == b"\x81\xE9" and b[6] == 0xE9:    # sub ecx, imm32; jmp rel32
            n, rel, size = struct.unpack_from("<I", b, 2)[0], struct.unpack_from("<i", b, 7)[0], 11
        else:
            continue
        out[a] = (n, a + size + rel)
    return out


def supplied():
    """Addresses already hooked by hand-written sources (src/, standalone/ except this file)."""
    got = set()
    paths = [os.path.join(d, f) for d, _, fs in os.walk(os.path.join(ROOT, "src")) for f in fs if f.endswith(".cpp")]
    paths += [os.path.join(ROOT, "standalone", f) for f in os.listdir(os.path.join(ROOT, "standalone"))
              if f.endswith(".cpp") and f != "adjustors.cpp"]
    for p in paths:
        got |= {int(x, 16) for x in re.findall(r"HOOK\(\s*(0x[0-9A-Fa-f]+)", open(p, errors="replace").read())}
    return got


def render(ts):
    lines = ["// Generated by tools/gen_adjustors.py: the exe's this-adjustor thunks (`sub ecx, N; jmp target`), which",
             "// IDA leaves outside any function. Standalone only; regenerate, do not edit.",
             '#include "globals.h"', '#include "hook.h"', ""]
    for a, (n, t) in ts.items():
        lines += [f"static void* const adjustorTarget_{a:08X} = reinterpret_cast<void*>(CSF_ADDR_FN(0x{t:08X}));",
                  f"static __declspec(naked) void Adjustor_{a:08X}() {{",
                  f"    __asm sub ecx, 0x{n:X}",
                  f"    __asm jmp dword ptr [adjustorTarget_{a:08X}]",
                  "}",
                  f'HOOK(0x{a:08X}, Adjustor_{a:08X}, "auto");', ""]
    return "\n".join(lines)


def main():
    have = supplied()
    ts = {a: v for a, v in thunks().items() if a not in have}
    text = render(ts)
    if "--check" in sys.argv:
        sys.exit(0 if os.path.exists(OUT) and open(OUT).read() == text else 1)
    open(OUT, "w").write(text)
    print(f"{len(ts)} adjustor thunks -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
