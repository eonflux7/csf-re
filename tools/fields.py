#!/usr/bin/env python3
"""Global structure recovery: one name per (class, offset), from every function's observations together.

Layouts are already global (tools/classes.py: offsets and access sizes over all of a class's methods). Names were
not: each grunt proposes field names for the fields its function touches (db/proposals.jsonl `field_names`,
e.g. {"CGuiPanel.field_0138": "childrenBegin"}), and they were never pooled. Here they are voted: spellings are
normalized (m_/p/b/sz prefixes, case) so childrenBegin / m_childrenBegin / pChildrenBegin agree, and an offset is
named when >= --min-votes proposals exist and >= --agree of them say the same thing. Names chosen by Opus/the
captain (db/types/classes.yaml `fields:`) always win; only named classes (conf >= 0.7) get fields.

  fields.py report               candidates per class (votes, agreement), nothing written
  fields.py apply [--min-votes 3] [--agree 0.6]   write consensus names to db/types/field_consensus.yaml
                                 (then: tools/rename_classes.py rewrites field_XXXX in src + regenerates the header)
  fields.py fixbuild               after rename_classes.py: name the field_XXXX references the build rejects
  fields.py coverage [--module M]  per module: share of `this`-relative field accesses in src/auto that go through a
                                 named field (named / (named + field_XXXX + CSF_AT on self)) - the "types first" gauge
"""
import argparse, collections, glob, json, os, re, sys
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(__file__))
YAML = os.path.join(ROOT, "db", "types", "classes.yaml")
GENERIC = re.compile(r"(?i)^(m_)?(field|unk|unknown|value|data|member|var|offset|dword|word|byte|flag|ptr|pointer)"
                     r"_?[0-9a-f]*$|_?[0-9a-f]{3,4}$")


def norm(n):
    """childrenBegin, m_childrenBegin, m_pChildrenBegin, pChildrenBegin -> childrenbegin"""
    n = re.sub(r"^m_", "", n)
    n = re.sub(r"^(p|b|n|sz|f|i|u|dw|psz|pp)(?=[A-Z])", "", n)
    return n.replace("_", "").lower()


def votes():
    out = collections.defaultdict(lambda: collections.defaultdict(collections.Counter))  # cls -> off -> norm -> spellings
    for l in open(os.path.join(ROOT, "db", "proposals.jsonl")):
        p = json.loads(l)
        for k, v in (p.get("field_names") or {}).items():
            m = re.match(r"(\w+)\.(?:field_)?(?:0x)?([0-9a-fA-F]+)$", str(k))
            if not m or not isinstance(v, str) or not re.fullmatch(r"[A-Za-z_]\w*", v) or GENERIC.search(v):
                continue
            out[m.group(1)][int(m.group(2), 16)][norm(v)] += 0  # ensure key
            out[m.group(1)][int(m.group(2), 16)][v] += 1
    return out


def consensus(min_votes, agree):
    """{class: {offset: (name, votes, total)}}"""
    res = {}
    for cls, offs in votes().items():
        for off, spell in offs.items():
            groups = collections.Counter()
            best_spelling = {}
            for s, n in spell.items():
                if n == 0:
                    continue
                groups[norm(s)] += n
                if n > best_spelling.get(norm(s), ("", 0))[1]:
                    best_spelling[norm(s)] = (s, n)
            total = sum(groups.values())
            if not total:
                continue
            g, n = groups.most_common(1)[0]
            if total >= min_votes and n / total >= agree:
                name = best_spelling[g][0]
                if not name.startswith("m_"):
                    name = "m_" + name
                res.setdefault(cls, {})[off] = (name, n, total)
    return res


def classes_yaml():
    return yaml.safe_load(open(YAML)) or {}


CONSENSUS = os.path.join(ROOT, "db", "types", "field_consensus.yaml")


def apply(min_votes, agree):
    """Write db/types/field_consensus.yaml {vtable: {offset: name}}: merged under classes.yaml's own `fields:` by
    gen_classes_h.load_names (classes.yaml - curated by Opus/the captain - is never rewritten)."""
    d = classes_yaml()
    by_name = {v["name"]: (f"{k:08x}" if isinstance(k, int) else str(k).lower())
               for k, v in d.items() if isinstance(v, dict) and v.get("conf", 0) >= 0.7}
    out, n_new = {}, 0
    for cls, offs in sorted(consensus(min_votes, agree).items()):
        key = by_name.get(cls)
        if key is None:
            continue
        own = {int(str(k), 16) for k in ((d.get(key) or d.get(int(key, 16)) or {}).get("fields") or {})}
        taken = set()
        for off, (name, n, total) in sorted(offs.items()):
            if off in own or name in taken:
                continue  # Opus/captain names win; one name per field
            out.setdefault(key, {})[f"{off:04x}"] = name
            taken.add(name)
            n_new += 1
    with open(CONSENSUS, "w") as fh:
        fh.write("# GENERATED by tools/fields.py apply: field names by consensus of the grunts' per-function proposals\n"
                 f"# (>= {min_votes} votes, >= {agree:.0%} agreement after normalizing spelling). classes.yaml fields win.\n")
        yaml.safe_dump(out, fh, sort_keys=True)
    print(f"{n_new} field names by consensus -> {os.path.relpath(CONSENSUS, ROOT)} "
          f"(min votes {min_votes}, agreement {agree:.0%}); run tools/rename_classes.py to apply")
    return n_new


def coverage(modules=None):
    """{module: (named, unnamed)} over src/auto files: accesses to self-> named members vs field_XXXX / CSF_AT(.., self, ..)."""
    import csv
    rows = {r["ea"]: r for r in csv.DictReader(open(os.path.join(ROOT, "db", "functions.csv")))}
    mods = {}
    mp = os.path.join(ROOT, "db", "modules.yaml")
    names = {m["id"]: m.get("name") or m["id"] for m in (yaml.safe_load(open(mp)) or [])} if os.path.exists(mp) else {}
    out = collections.defaultdict(lambda: [0, 0])
    for p in glob.glob(os.path.join(ROOT, "src", "auto", "*.cpp")):
        ea = os.path.basename(p)[:8]
        mod = rows.get(ea, {}).get("module") or "?"
        mname = names.get(mod, mod)
        if modules and mod not in modules and mname not in modules:
            continue
        src = re.sub(r"//[^\n]*|/\*.*?\*/", "", open(p).read(), flags=re.S)
        un = len(re.findall(r"\bself->field_[0-9a-f]{4}\b", src)) + len(re.findall(r"CSF_AT\([^,]+,\s*self\s*,", src))
        nm = len(re.findall(r"\bself->(m_\w+|[a-z]\w*)\b(?!\s*\()", src)) - len(re.findall(r"\bself->vtbl\b", src))
        out[mname][0] += max(nm, 0)
        out[mname][1] += un
    return out


def fixbuild():
    """After a rename pass: files that still say obj->field_XXXX for a field that now has a name (rename_classes
    only rewrites files with a single class type). Takes the compiler's own diagnosis (no member named 'field_XXXX'
    in 'Class') and substitutes Class's name for that offset on exactly that line. Repeats until the build is clean."""
    import subprocess
    from gen_classes_h import load_names, C
    names = load_names()
    by_cls = {v["name"]: k for k, v in names.items()}
    fixed = 0
    for _ in range(10):
        r = subprocess.run(["ninja", "-C", os.path.join(ROOT, "build"), "-k", "0"], capture_output=True, text=True)
        errs = re.findall(r"^(\S+?\.cpp)\((\d+),\d+\): error: no member named '(field_([0-9a-f]{4}))' in '(\w+)'",
                          r.stdout + r.stderr, re.M)
        if not errs:
            break
        for path, line, fld, off, cls in set(errs):
            vt, o, name = by_cls.get(cls), int(off, 16), None
            while vt and not name:  # the field may be named on a base
                f = {int(str(k), 16): v for k, v in (names.get(vt, {}).get("fields") or {}).items()}
                name = f.get(o)
                vt = C.get(vt, {}).get("base")
            if not name:
                continue
            name = name.split()[-1]  # "legacy::string m_str" -> m_str
            lines = open(path).read().split("\n")
            lines[int(line) - 1] = re.sub(rf"\b{fld}\b", name, lines[int(line) - 1])
            open(path, "w").write("\n".join(lines))
            fixed += 1
    print(f"{fixed} field references fixed after the rename pass")
    return fixed


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["report", "apply", "coverage", "fixbuild"])
    ap.add_argument("--min-votes", type=int, default=3)
    ap.add_argument("--agree", type=float, default=0.6)
    ap.add_argument("--module")
    a = ap.parse_args()
    if a.cmd == "report":
        for cls, offs in sorted(consensus(a.min_votes, a.agree).items()):
            print(cls)
            for off, (name, n, total) in sorted(offs.items()):
                print(f"  +0x{off:03X} {name:32s} {n}/{total}")
    elif a.cmd == "apply":
        apply(a.min_votes, a.agree)
    elif a.cmd == "fixbuild":
        fixbuild()
    else:
        cov = coverage(set(a.module.split(",")) if a.module else None)
        tn = tu = 0
        for m, (nm, un) in sorted(cov.items(), key=lambda x: -(x[1][0] + x[1][1])):
            tn, tu = tn + nm, tu + un
            if nm + un:
                print(f"  {m:32s} {100 * nm / (nm + un):5.1f}% named  ({nm} named / {un} raw self accesses)")
        print(f"total: {100 * tn / max(tn + tu, 1):.1f}% of self-relative field accesses go through a named field")


if __name__ == "__main__":
    main()
