#!/usr/bin/env python3
"""Emit fatal address-keyed traps from a fresh linktest inventory, never real slots.

Use --objects too to independently verify the list against the actual COFF link
inputs (data image and initializer dependencies included, generated traps excluded).
"""
import argparse
import collections
import concurrent.futures
import csv
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))


def generate(inventory, output, objects=None):
    report = json.loads(inventory.read_text())
    if report['failed'] or report['duplicates']:
        raise ValueError('cannot stub a failed or duplicate implementation inventory')
    defined = {int(a, 16) for a in report['defined_functions']}
    missing = {int(a, 16): kind for kind, group in report['unresolved_functions'].items() for a in group}
    if defined & set(missing):
        raise ValueError('attempt to stub an already defined slot')
    if objects is not None:
        from linktest import symbols, demangle, SLOT
        all_defs, all_refs = set(), set()
        paths = objects.read_text().splitlines()
        if not paths or any(not Path(p).is_file() for p in paths):
            raise ValueError('missing/empty actual object inventory')
        slot_definitions = collections.Counter()
        with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
            for d, u in pool.map(symbols, paths):
                all_defs |= d
                all_refs |= u
                slot_definitions.update(s for s in d if 'fn_slot@' in s)
        if any(n > 1 for n in slot_definitions.values()):
            raise ValueError('duplicate actual function slot definitions')
        names = demangle(sorted(s for s in all_defs | all_refs if 'csf@@' in s))
        actual_defined, actual_missing = set(), set()
        for s, name in names.items():
            m = SLOT.search(name)
            if m and m[1] == 'fn_slot':
                (actual_defined if s in all_defs else actual_missing).add(int(m[2]))
        if defined != actual_defined or set(missing) != actual_missing:
            raise ValueError('stale/wrong linktest inventory')
    with (ROOT / 'db/functions.csv').open() as stream:
        functions = {int(r['ea'], 16): r for r in csv.DictReader(stream)}
    rows = [dict(address=f'0x{a:08X}', kind=missing[a],
                 name=functions.get(a, {}).get('name') or ('<unnamed>' if a in functions else '<not in db/functions.csv>'))
            for a in sorted(missing)]
    output.mkdir(parents=True, exist_ok=True)
    code = ['// Generated by tools/stubgen.py. DO NOT EDIT. Fatal, NEVER a fallback result.',
            '#include "hook.h"', '#include "runtime.h"', '#include <cstdio>', '#include <cstdlib>',
            'namespace csf {',
            '// Inspectable even if stderr is unavailable; assigned before abort.',
            'volatile uintptr_t unresolved_address = 0;',
            'const char* volatile unresolved_name = nullptr;',
            'namespace {', 'struct Missing { uintptr_t address; const char* name; const char* kind; };',
            'const Missing missing[] = {']
    for r in rows:
        code.append(f'    {{CSF_ADDR_ORIGINAL({r["address"]}), {json.dumps(r["name"])}, {json.dumps(r["kind"])}}},')
    # A dummy metadata row permits the empty inventory without a zero-size array.
    code += ['    {0, nullptr, nullptr}', '};', '}',
             '[[noreturn]] void unresolved(uintptr_t address) {',
             '    const char* name = "<unknown>";', '    const char* kind = "unknown";',
             '    for (const auto& row : missing) if (row.address == address) {',
             '        name = row.name; kind = row.kind; break;', '    }',
             '    unresolved_address = address;', '    unresolved_name = name;',
             '    std::fprintf(stderr, "csf: UNRESOLVED 0x%08lX %s [%s]\\n",',
             '                 static_cast<unsigned long>(address), name, kind);',
             '    std::fflush(stderr);', '    std::abort();', '}', '} // namespace csf']
    for r in rows:
        a = int(r['address'], 16)
        # Extra arguments/registers do not matter: no trap returns to its caller.
        code += [f'[[noreturn]] static void __cdecl trap_{a:08X}() {{',
                 f'    csf::unresolved(CSF_ADDR_ORIGINAL({r["address"]}));', '}',
                 f'HOOK({r["address"]}, trap_{a:08X}, "unresolved");']
    (output / 'stubs.cpp').write_text('\n'.join(code) + '\n')
    (output / 'stubs.json').write_text(json.dumps(dict(count=len(rows),
        counts=dict(collections.Counter(r['kind'] for r in rows)), slots=rows), indent=1) + '\n')
    print('fatal trap slots: ' + ', '.join(f'{k} {v}' for k, v in sorted(collections.Counter(r['kind'] for r in rows).items())))


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--linktest', type=Path, required=True)
    ap.add_argument('--output', type=Path, required=True)
    ap.add_argument('--objects', type=Path, required=True,
                    help='independent verification against actual un-stubbed objects (required for generation)')
    args = ap.parse_args()
    generate(args.linktest, args.output, args.objects)
