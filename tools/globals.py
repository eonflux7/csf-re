#!/usr/bin/env python3
"""Collect CSF_GLOBAL declarations from src/ into db/globals.yaml (addr, name, type, uses, alt names).

Existing entries with src: opus|user are kept as-is. Generic names (containing the address, g_Value*, g_Global*)
lose to descriptive ones; among descriptive names the most used wins, the rest are listed under `alt` for review.
The packet builder (tools/packet.py) shows these names to grunts, so later functions reuse them.
"""
import collections, glob, os, re
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, "db", "globals.yaml")
DECL = re.compile(r"CSF_GLOBAL\(\s*(.+?)\s*,\s*(\w+)\s*,\s*0x([0-9A-Fa-f]+)\s*\)")


def generic(name, addr):
    """True when the name says nothing beyond the address: the address with an optional g_Value/g_Global-style
    prefix. g_FloatZero_0082D4CC is descriptive (beats g_Value_0082D4CC)."""
    n = re.sub(rf"_?0*{addr:x}$", "", name.lower())
    return n in ("", "g") or re.fullmatch(r"g_?(value|global|globalvalue|globalobject|var|data|unk|dword|flag)\d*", n) is not None


def main():
    seen = collections.defaultdict(collections.Counter)
    types = collections.defaultdict(collections.Counter)
    for p in glob.glob(os.path.join(ROOT, "src", "**", "*.cpp"), recursive=True):
        for t, n, a in DECL.findall(open(p).read()):
            seen[int(a, 16)][n] += 1
            types[int(a, 16)][t] += 1
    old = {int(g["addr"]): g for g in (yaml.safe_load(open(PATH)) if os.path.exists(PATH) else None) or []}
    out = []
    for addr in sorted(set(seen) | set(old)):
        g = old.get(addr)
        if g and g.get("src") in ("opus", "user"):
            out.append(g)
            continue
        names = sorted(seen[addr].items(), key=lambda kv: (generic(kv[0], addr), -kv[1], kv[0]))
        if not names:
            continue
        e = dict(addr=addr, name=names[0][0], type=types[addr].most_common(1)[0][0],
                 uses=sum(seen[addr].values()), src="auto")
        if len(names) > 1:
            e["alt"] = [n for n, _ in names[1:]]
        out.append(e)
    with open(PATH, "w") as f:
        f.write("# Game globals. Generated by tools/globals.py from CSF_GLOBAL declarations; set src: opus|user to pin.\n")
        for e in out:  # one flow mapping per line; PyYAML reads 0x... as int
            rest = yaml.safe_dump({k: v for k, v in e.items() if k != "addr"}, default_flow_style=True,
                                  sort_keys=False, width=1000).strip()[1:]
            f.write(f"- {{addr: 0x{e['addr']:08X}, {rest}\n")
    print(f"{len(out)} globals, {sum(1 for e in out if 'alt' in e)} with conflicting names")


if __name__ == "__main__":
    main()
