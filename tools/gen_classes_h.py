#!/usr/bin/env python3
"""Generate src/types/auto_classes.h from db/classes.json (+ db/class_names.yaml overrides when present).

Each class becomes `struct C_<vtable>` (or its assigned name) with field_XXXX members typed by access size,
float when accessed by FPU/SSE ops; overlapping/odd accesses fall back to byte padding. Bases are embedded as
the first member when the base's size is known. sizeof static_asserts where the allocation size is known.
Regenerate after any classes.json / names change. Hand-designed types go in src/types/*.h and win over these.
"""
import json, os
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
C = {c["vtable"]: c for c in json.load(open(os.path.join(ROOT, "db", "classes.json")))}
names_path = os.path.join(ROOT, "db", "class_names.yaml")
NAMES = yaml.safe_load(open(names_path)) if os.path.exists(names_path) else {}
NAMES = {f"{int(k):08x}" if isinstance(k, int) else k.lower(): v for k, v in (NAMES or {}).items()}


def name(vt):
    return NAMES.get(vt, f"C_{vt}")


def ctype(size, rw):
    if "f" in rw and size == 4:
        return "float"
    if "f" in rw and size == 8:
        return "double"
    return {1: "uint8_t", 2: "uint16_t", 4: "uint32_t", 8: "uint64_t"}.get(size)


order, seen = [], set()


def visit(vt):
    if vt in seen or vt not in C:
        return
    seen.add(vt)
    if C[vt]["base"]:
        visit(C[vt]["base"])
    order.append(vt)


for vt in sorted(C):
    visit(vt)

out = ["// GENERATED by tools/gen_classes_h.py from db/classes.json — do not edit by hand.",
       "// Rename classes in db/class_names.yaml; hand-designed layouts go in src/types/.",
       "#pragma once", "#include <cstddef>", "#include <cstdint>", "", "#pragma pack(push, 1)"]
emitted, extent = set(), {}


def field_end(c):
    return max([int(o, 16) + f["size"] for o, f in c["fields"].items()] + [4])


for vt in order:
    c = C[vt]
    b = c["base"]
    # embed base only if already declared (no cycles) and it fits inside our known size
    if not (b in emitted and (not c["size"] or extent[b] <= c["size"])):
        b = None
    extent[vt] = c["size"] or max(field_end(c), extent[b] if b else 4)
    emitted.add(vt)
    start = extent[b] if b else 4
    lines = [f"struct {name(vt)}" + (f" : {name(b)}" if b else "") + " {"]
    if not b:
        lines.append("    void** vtbl;")
    cur = start
    end = extent[vt]
    for o, f in sorted(((int(o, 16), f) for o, f in c["fields"].items())):
        if o < cur or o + f["size"] > end:
            continue
        t = ctype(f["size"], f["rw"])
        if not t or o % min(f["size"], 4):
            continue
        if o > cur:
            lines.append(f"    uint8_t pad_{cur:04x}[0x{o - cur:x}];")
        lines.append(f"    {t} field_{o:04x};")
        cur = o + f["size"]
    if end > cur:
        lines.append(f"    uint8_t pad_{cur:04x}[0x{end - cur:x}];")
    lines.append("};")
    if c["size"]:
        lines.append(f"static_assert(sizeof({name(vt)}) == 0x{c['size']:x});")
    out += lines + [""]
out.append("#pragma pack(pop)")
os.makedirs(os.path.join(ROOT, "src", "types"), exist_ok=True)
open(os.path.join(ROOT, "src", "types", "auto_classes.h"), "w").write("\n".join(out) + "\n")
print(f"wrote {len(order)} classes")
